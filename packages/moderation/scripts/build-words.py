SEP = re.compile(r"[,，|=\t;；、]")
CTRL = re.compile(r"[\u0000-\u001f\u007f-\u009f​-‏ -‮﻿]")


def norm(s: str) -> str:
    return unicodedata.normalize("NFKC", s).strip().lower()


def ok(w: str) -> bool:
    if not w or SEP.search(w) or CTRL.search(w):
        return False
    if w.isdigit():
        return False
    if w.isascii():
        return 3 <= len(w) <= 20 and not re.search(r"\s", w) and w not in COMMON_ASCII
    return 2 <= len(w) <= 20 and w not in COMMON


def main() -> None:
    vocab, ref = sys.argv[1], sys.argv[2]
    seen: set = set()
    stats = {"source": "https://github.com/konsheng/Sensitive-lexicon", "ref": ref, "categories": {}}
    os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
    ts = [
        "// GENERATED by scripts/build-words.py — do not edit. Source: konsheng/Sensitive-lexicon (MIT), see ../SOURCES.md",
        "",
    ]
    meta = []
    for cid, files, default, label in CATEGORIES:
        raw = 0
        words = []
        for f in files:
            with open(os.path.join(vocab, f), encoding="utf-8", errors="replace") as fh:
                for line in fh:
                    raw += 1
                    w = norm(line)
                    if ok(w) and w not in seen:
                        seen.add(w)
                        words.append(w)
        words.sort()
        with open(os.path.join(ROOT, "data", f"{cid}.txt"), "w", encoding="utf-8") as out:
            out.write("\n".join(words) + "\n")
        stats["categories"][cid] = {"files": files, "raw": raw, "kept": len(words), "default": default}
        ts.append(f"export const {cid.upper()} = {json.dumps(chr(10).join(words), ensure_ascii=False)};")
        meta.append(f"  {{ id: '{cid}', label: '{label}', default: {'true' if default else 'false'}, words: {cid.upper()} }},")
    ts += [
        "",
        "export const CATEGORY_DATA: ReadonlyArray<{ id: string; label: string; default: boolean; words: string }> = [",
        *meta,
        "];",
        "",
    ]
    with open(os.path.join(ROOT, "src", "words.generated.ts"), "w", encoding="utf-8") as out:
        out.write("\n".join(ts))
    with open(os.path.join(ROOT, "data", "STATS.json"), "w", encoding="utf-8") as out:
        json.dump(stats, out, ensure_ascii=False, indent=2)
    print(json.dumps(stats["categories"], ensure_ascii=False))


if __name__ == "__main__":
    main()
