"""Dev-time generator for @starnote/moderation word lists (outputs are committed; not part of `pnpm build`).

    python3 -I packages/moderation/scripts/build-words.py <Sensitive-lexicon checkout>/Vocabulary <commit-or-date>

The downloaded lexicon is untrusted data: it is only read as UTF-8 text, one word per line.
Cleaning: NFKC + lower-case, strip, drop empty / separator-bearing / control-char lines, length filter
(2..20 chars; pure ASCII needs >= 3), drop pure digits, drop words on COMMON (too generic for an
article body), de-duplicate across categories (first category wins, in CATEGORIES order).
Writes data/<category>.txt, src/words.generated.ts and data/STATS.json.
"""
